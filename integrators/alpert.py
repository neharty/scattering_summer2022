import numpy as np
from abc import ABC, abstractmethod

class alpert(ABC):
    '''
        Template class for alpert methods
    '''
    def __init__(self, nodes, weights, dist, order):
        self.nodes = nodes
        self.weights = weights
        self.dist = dist
        self.order = order
        self.M = order + 3
        
        self.nodemat = np.hstack((-np.flip(nodes), nodes))
        self.weightmat = np.hstack((np.flip(weights), weights))
        
